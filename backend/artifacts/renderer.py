"""将模型草稿渲染为稳定的任务文档格式。"""

from __future__ import annotations

from datetime import datetime, timezone


def _date() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")


def render_requirement_document(
    draft: str,
    document_id: str,
    title: str,
    project_path: str,
    task_description: str,
) -> str:
    """把需求分析草稿放入参考 T 文档的固定十章结构。"""
    return f"""# {title} - 需求概括

**文档编号**: {document_id}
**需求日期**: {_date()}
**需求类型**: DEV
**目标项目**: {project_path}

---

## 1. 任务概述

### 1.1 任务目标
{task_description}

### 1.2 任务范围
以用户确认的需求和以下分析草稿为准；未明确内容不得擅自扩展。

### 1.3 核心交付物
{draft}

## 2. 技术架构

### 2.1 数据流设计
请根据源码、需求和 RAG 证据补充数据输入、处理、输出链路。

### 2.2 模块边界
请列出允许修改、只读分析和明确禁止修改的模块。

### 2.3 状态流转规则
请列出工作流状态、业务状态及其转换条件；未指定时标注“未指定”。

## 3. 接口/功能设计

### 3.1 输入格式
未指定的输入字段必须明确标注“未指定”。

### 3.2 输出格式
必须列出用户可见产物和机器可验证结果。

### 3.3 用户交互或调用方式
必须列出启动、使用和异常时的交互方式。

## 4. 业务逻辑

### 4.1 主流程
按执行顺序列出步骤。

### 4.2 异常流程
列出失败、超时、权限和输入不完整时的行为。

### 4.3 边界条件
列出空输入、重复执行、并发和兼容性边界。

## 5. 数据结构与存储

### 5.1 数据模型
未涉及时标注“不适用”。

### 5.2 字段说明
列出新增或变更字段、类型、必填性和来源。

### 5.3 持久化要求
列出数据库、文件、缓存或 localStorage 要求。

## 6. 外部依赖与集成

### 6.1 依赖组件
只列出现有项目或用户明确要求的依赖。

### 6.2 API 或工具调用
列出接口、工具和权限边界。

### 6.3 配置要求
列出环境变量、端口和运行前提。

## 7. 错误处理

### 7.1 错误场景
列出可预期错误。

### 7.2 错误响应
列出用户和机器可见的错误格式。

### 7.3 降级策略
未指定时标注“未指定”。

## 8. 技术约束

### 8.1 项目红线
遵循项目 AGENTS.md 及用户明确约束。

### 8.2 代码规范
遵循现有项目风格和类型约束。

### 8.3 向后兼容
列出不得破坏的现有行为。

### 8.4 禁止修改范围
列出 protected_paths；没有时写“未指定”。

## 9. 验收标准

### 9.1 功能验收
必须是可执行、可观察的验收项。

### 9.2 数据验收
列出数据结构、文件和持久化验收项。

### 9.3 兼容性验收
列出回归和兼容性验收项。

### 9.4 验证命令
只列出白名单验证命令。

## 10. 参考文档

- 参见项目 AGENTS.md
- 任务描述：{task_description}

---

**文档生成**: Just_codding Agent
**最后更新**: {_date()}
"""


def render_diagnosis_document(
    draft: str,
    document_id: str,
    title: str,
    project_path: str,
    description: str,
) -> str:
    """把诊断草稿渲染为参考 D 文档的固定结构。"""
    return f"""# {title} - 问题分析报告

**报告编号**: {document_id}
**分析日期**: {_date()}
**分析师**: Just_codding Agent
**问题状态**: 修复中
**目标项目**: {project_path}

---

## 📋 问题还原与影响范围评估

### 1.1 问题现象
{description}

### 1.2 复现步骤
请基于用户描述、日志和工具结果逐步列出；未知步骤必须标注“未确认”。

### 1.3 发生频率
未确认。不得在没有运行证据时声称“100%可复现”。

### 1.4 影响范围
列出受影响模块、用户范围、功能影响和数据风险。

### 1.5 环境信息
列出版本、运行环境、配置和相关服务。

## 🔍 上下文信息收集

### 2.1 相关代码文件
列出文件路径和行号。

### 2.2 关键函数/类名
列出实际参与数据流或控制流的符号。

### 2.3 历史修复记录
列出可验证的历史任务或 BUG 编号。

## 🎯 根因定位与论据验证

### 3.1 根因分析
{draft}

### 3.2 可追溯论据链
每条论据必须包含 source、reference、detail。

### 3.3 排除其他可能性
列出已检查但被排除的原因及排除依据。

## 🛠️ 逻辑修复方向建议

### 4.1 核心修复方向
只写修复方向，不直接编写业务修复代码。

### 4.2 修复优先级
使用 P0/P1/P2，并说明排序依据。

### 4.3 验证标准
列出功能、回归、日志和运行时验证项。

## 📊 影响范围与修复优先级

### 5.1 影响维度评估
分别评估功能、用户体验、数据完整性和系统稳定性。

### 5.2 预期修复效果
列出修复完成后可观察的结果。

## 🔗 参考文档

- 参见项目 AGENTS.md
- 问题描述：{description}

---

**报告生成**: Just_codding Agent
**最后更新**: {_date()}
"""
